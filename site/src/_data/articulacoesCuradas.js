/**
 * Filtra articulações cujos source/target existem realmente no dataset.
 * Validação adicional defensiva — o script de consolidação já verificou IDs
 * contra latest.json no momento da geração, mas a função protege contra drift
 * futuro do dataset.
 */
export default function curadasValidas(policies) {
  const ids = new Set(policies.map((p) => p.id_interno).filter(Boolean));
  const validas = articulacoes.filter(
    (a) => ids.has(a.source) && ids.has(a.target)
  );
  const ausentes = articulacoes.length - validas.length;
  if (ausentes > 0) {
    console.info(`[articulacoesCuradas] ${validas.length} válidas, ${ausentes} com IDs não encontrados em latest.json (revisar)`);
  }
  return validas;
}

